#!/usr/bin/env python3
"""name_guard.py -- the precedent's vendor and its products are never named.

Every word and every pair of neighbouring words of a text (a tracked file, a
tracked path, a commit message) is lower-cased and hashed; a hash in FORBIDDEN
is a hit. The names themselves are not written anywhere, not even here.

One exception (N62), kept in ALLOWED: the UI component toolkit is published
under the vendor's npm scope, and a dependency's package name cannot be
changed here. The scope token may appear in the two package files and on
import lines of .ts, .tsx and .css files under ui/ and shell/. Lines elsewhere
that carry the token today are listed in quality/name-guard-baseline.txt
(`path:hash of the line`), a list that only shrinks and holds nothing else.

    name_guard.py --tree                 every tracked file and path
    name_guard.py --staged               the staged files and paths (pre-commit)
    name_guard.py --message FILE         a commit message
    name_guard.py --write-baseline       rewrite the baseline from today's lines
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import os
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "quality" / "name-guard-baseline.txt"
HEADER = (
    "# GENERATED by tools/name_guard.py --write-baseline -- do not edit, do not merge by hand.\n"
    "# path:hash of a line that carries the allowed toolkit scope outside the allowed places.\n"
    "# The list may only shrink.\n"
)

#: sha256 of a lower-cased word or of two neighbouring words joined by a space.
FORBIDDEN = frozenset({
    "f65e6c3116f5bdf9ac5df827fd44cfa4674a980da8b551b98f5e771f831cbbb4",
    "dfb316701857783dac69a14d1fe3fd60cff21d56e830baf7f0e3871bd73eee39",
    "e5af78f00ddc515a3685c1b0f392c4241b2cb36415a87bdaed229b598ecd74cb",
    "8d3aa1a6f227d714692a9d5a7fbbda496fb09f17f7207a11ffd0a4cca6cf35b7",
    "bc7bc94c4c006e73135fce32b7e4697d79cf50d8c7740ec19788ac569b22e285",
    "1cd7fc4574336a5b48d60a2ac740bb7b4e3441e80879ed3f22e84496943413a7",
    "b23797ab7591e438535abd2dd419609e558aa6716e58fe4d87d35b4368664b75",
    "5ea01f8ad3ddeae6b483e0f4e6c17482c878409a36391235ca0b993f541a38f0",
    "7c30be79017a5bd070cbc3b5623b3e1734cb00ef6fba7789f28d68dfa4c2dcbf",
})

#: Tests add a harmless word to the list through this variable (sha256 hex, comma separated),
#: so a test can plant a "forbidden" word without any name being written down.
FORBIDDEN = FORBIDDEN | frozenset(h for h in os.environ.get("ELYSIUM_NAME_GUARD_EXTRA", "").split(",") if h)

#: The UI component toolkit is published under this scope; a dependency's package
#: name cannot be changed here. The scope passes only in the two package files and
#: on import lines (`import:<glob>` limits the import lines to files under that glob).
ALLOWED = {
    "bc7bc94c4c006e73135fce32b7e4697d79cf50d8c7740ec19788ac569b22e285": (
        "ui/package.json", "ui/package-lock.json", "import:ui/**", "import:shell/**"),
}

_WORD = re.compile(r"[a-z0-9]+")
_CAMEL = re.compile(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+")
_IMPORT = re.compile(r"""^\s*(?:import\b|export\b[^=]*\bfrom\b|\}\s*from\b|@import\b)""")
_IMPORT_SUFFIXES = (".ts", ".tsx", ".css")


class Hit(NamedTuple):
    path: str
    line: int
    text: str
    digest: str

    @property
    def key(self) -> str:
        return f"{self.path}:{hashlib.sha256(self.text.strip().encode()).hexdigest()[:12]}"


def digests(text: str) -> set[str]:
    """Hashes of every word and word pair in `text`, in both tokenisations."""
    found: set[str] = set()
    for words in (_WORD.findall(text.lower()), [w.lower() for w in _CAMEL.findall(text)]):
        for item in (*words, *(f"{a} {b}" for a, b in zip(words, words[1:], strict=False))):
            found.add(hashlib.sha256(item.encode()).hexdigest())
    return found


def _allowed(digest: str, path: str, line: str) -> bool:
    for rule in ALLOWED.get(digest, ()):
        if rule.startswith("import:"):
            if (path.endswith(_IMPORT_SUFFIXES) and fnmatch.fnmatch(path, rule[len("import:"):])
                    and _IMPORT.search(line)):
                return True
        elif path == rule:
            return True
    return False


def check_text(text: str, path: str = "") -> list[Hit]:
    """Hits in `text`, as if it were the file `path` (empty: no exception applies)."""
    hits = []
    for number, line in enumerate(text.split("\n"), start=1):
        for digest in digests(line) & FORBIDDEN:
            if not (path and _allowed(digest, path, line)):
                hits.append(Hit(path, number, line, digest))
    return hits


def check_path(path: str) -> list[Hit]:
    return [Hit(path, 0, path, d) for d in digests(path) & FORBIDDEN]


def read_baseline() -> Counter[str]:
    if not BASELINE.exists():
        return Counter()
    return Counter(line for line in BASELINE.read_text().splitlines()
                   if line.strip() and not line.startswith("#"))


def _git(*arguments: str) -> bytes:
    return subprocess.run(  # noqa: S603, S607 -- fixed argument list, no shell
        ["git", *arguments], capture_output=True, check=True, cwd=ROOT).stdout  # noqa: S607 -- fixed command


def _text(raw: bytes) -> str | None:
    if b"\0" in raw:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def tracked_paths() -> list[str]:
    return [p for p in _git("ls-files", "-z").decode().split("\0") if p]


def staged_paths() -> list[str]:
    out = _git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z").decode()
    return [p for p in out.split("\0") if p]


def scan(paths: list[str], from_index: bool) -> list[Hit]:
    hits: list[Hit] = []
    for path in paths:
        hits.extend(check_path(path))
        raw = _git("show", f":{path}") if from_index else (ROOT / path).read_bytes()
        text = _text(raw)
        if text is not None and digests(text) & FORBIDDEN:
            hits.extend(check_text(text, path))
    return hits


def unlisted(hits: list[Hit], baseline: Counter[str]) -> list[Hit]:
    """Hits not covered by the baseline (which can cover only the allowed scope token)."""
    left = Counter(baseline)
    fresh = []
    for hit in hits:
        if hit.digest in ALLOWED and left[hit.key] > 0:
            left[hit.key] -= 1
        else:
            fresh.append(hit)
    return fresh


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--tree", action="store_true")
    group.add_argument("--staged", action="store_true")
    group.add_argument("--message", metavar="FILE")
    group.add_argument("--write-baseline", action="store_true")
    args = parser.parse_args(argv)

    if args.message:
        hits = check_text(Path(args.message).read_text())
        baseline: Counter[str] = Counter()
    elif args.staged:
        hits, baseline = scan(staged_paths(), True), read_baseline()
    else:
        hits, baseline = scan(tracked_paths(), False), read_baseline()
    if args.write_baseline:
        scope_only = [h for h in hits if h.digest in ALLOWED]
        BASELINE.parent.mkdir(exist_ok=True)
        BASELINE.write_text(HEADER + "".join(sorted(h.key + "\n" for h in scope_only)))
        print(f"{len(scope_only)} line(s) in the baseline; {len(hits) - len(scope_only)} not baselinable")
        return 1 if len(hits) > len(scope_only) else 0

    fresh = unlisted(hits, baseline)
    for hit in fresh:
        where = f"{hit.path}:{hit.line}" if hit.line else (hit.path or "message")
        print(f"{where}: a name the repository must not carry (write \"the precedent\")")
    return 1 if fresh else 0


if __name__ == "__main__":
    sys.exit(main())
