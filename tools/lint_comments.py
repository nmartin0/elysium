#!/usr/bin/env python3
"""lint_comments.py -- comments carry rules, not history.

In src/**.py, comments and docstrings must not carry ticket codes, dates,
names of planning documents or conversation. What exists today is listed in
quality/comment-lint-baseline.txt (`path:hash of the line`) and may only
shrink; a hit that is not in the list fails.

    lint_comments.py --check [--staged]   exit 1 on a hit not in the baseline
                                          (--staged: only the staged files)
    lint_comments.py --write-baseline     rewrite the baseline from today's hits
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import io
import re
import subprocess
import sys
import tokenize
from collections import Counter
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "src"
BASELINE = ROOT / "quality" / "comment-lint-baseline.txt"
HEADER = (
    "# GENERATED by tools/lint_comments.py --write-baseline -- do not edit, do not merge by hand.\n"
    "# path:hash of the line. The list may only shrink; on a conflict, regenerate.\n"
)
_MONTHS = "January|February|March|April|May|June|July|August|September|October|November|December"
PATTERNS = {
    "ticket code": re.compile(r"\b(?:GOLD|WIRED|DEP|AUD|SEC|AL|BLK|R|E|LB|NEW|F)-\d+"),
    "date": re.compile(rf"\b\d{{1,2}} (?:{_MONTHS})\b|\b\d{{4}}-\d{{2}}-\d{{2}}\b"),
    "planning file": re.compile(
        r"\b(?:ROADMAP|BLOCKING|HOT_RELOAD|SCALABILITY)\b|planning file|\bstep \d+[a-z]?\b", re.I),
    "conversation": re.compile(r"\bthe owner\b|\bI said\b|\bthis session\b|\breviewer said\b", re.I),
}


class Hit(NamedTuple):
    path: str
    line: int
    text: str
    rule: str

    @property
    def key(self) -> str:
        return f"{self.path}:{hashlib.sha1(self.text.strip().encode()).hexdigest()[:12]}"  # noqa: S324 -- a label, not security


def _prose(source: str) -> list[tuple[int, str]]:
    """(line number, text) of every comment line and docstring line."""
    lines: list[tuple[int, str]] = []
    try:
        for token in tokenize.generate_tokens(io.StringIO(source).readline):
            if token.type == tokenize.COMMENT:
                lines.append((token.start[0], token.string))
        tree = ast.parse(source)
    except (tokenize.TokenError, SyntaxError, IndentationError):
        return lines
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            first = node.body[0] if node.body else None
            if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                for offset, text in enumerate(first.value.value.split("\n")):
                    lines.append((first.value.lineno + offset, text))
    return lines


def scan_file(path: Path) -> list[Hit]:
    relative = str(path.relative_to(ROOT))
    hits = []
    for number, text in _prose(path.read_text()):
        for rule, pattern in PATTERNS.items():
            if pattern.search(text):
                hits.append(Hit(relative, number, text, rule))
                break
    return hits


def source_files() -> list[Path]:
    return sorted((ROOT / SOURCE).rglob("*.py"))


def staged_files() -> list[Path]:
    result = subprocess.run(  # noqa: S603, S607 -- fixed argument list, no shell
        ["git", "diff", "--cached", "--name-only", "--diff-filter=ACM"],  # noqa: S607 -- fixed command
        capture_output=True, text=True, check=True, cwd=ROOT)
    return [ROOT / name for name in result.stdout.splitlines()
            if name.startswith(SOURCE + "/") and name.endswith(".py")]


def read_baseline() -> Counter[str]:
    if not BASELINE.exists():
        return Counter()
    return Counter(line for line in BASELINE.read_text().splitlines()
                   if line.strip() and not line.startswith("#"))


def new_hits(hits: list[Hit], baseline: Counter[str]) -> list[Hit]:
    allowed = Counter(baseline)
    fresh = []
    for hit in hits:
        if allowed[hit.key] > 0:
            allowed[hit.key] -= 1
        else:
            fresh.append(hit)
    return fresh


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--write-baseline", action="store_true")
    parser.add_argument("--staged", action="store_true")
    args = parser.parse_args(argv)

    if args.write_baseline:
        hits = [h for f in source_files() for h in scan_file(f)]
        BASELINE.parent.mkdir(exist_ok=True)
        BASELINE.write_text(HEADER + "".join(sorted(h.key + "\n" for h in hits)))
        print(f"{len(hits)} hit(s) in the baseline")
        return 0

    files = staged_files() if args.staged else source_files()
    hits = [h for f in files for h in scan_file(f)]
    baseline = read_baseline()
    if args.staged:
        # Only these files are scanned, so only their share of the baseline applies.
        prefixes = tuple(str(f.relative_to(ROOT)) + ":" for f in files)
        baseline = Counter({k: v for k, v in baseline.items() if k.startswith(prefixes)})
    fresh = new_hits(hits, baseline)
    for hit in fresh:
        print(f"{hit.path}:{hit.line}: {hit.rule}: {hit.text.strip()}")
    if fresh:
        print(f"{len(fresh)} comment hit(s) not in the baseline: say the rule, not the history.")
    return 1 if fresh else 0


if __name__ == "__main__":
    sys.exit(main())
