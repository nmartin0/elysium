#!/usr/bin/env python3
"""ruff_baseline.py -- today's ruff offenders, listed per file, shrinking only.

The rules BLE, S and C901 are on for everything. Code that already breaks
them is listed per file in the generated block of
[tool.ruff.lint.per-file-ignores] in pyproject.toml, from the list in
quality/ruff-ignores.txt (one line per file and rule: `path RULE count`).

    ruff_baseline.py --write    count the offenders with the generated block
                                removed, then rewrite the list and the block
    ruff_baseline.py --check    exit 1 when a file has more of a rule than the
                                list allows (or none listed), or when the
                                block in pyproject.toml is not the list

Because the block silences ruff for a listed file, a new offence in a listed
file is found here, not by ruff: the count rises above the list.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = ROOT / "pyproject.toml"
BASELINE = ROOT / "quality" / "ruff-ignores.txt"
BEGIN = "# BEGIN GENERATED per-file-ignores (tools/ruff_baseline.py --write)\n"
END = "# END GENERATED per-file-ignores\n"
HEADER = (
    "# GENERATED by tools/ruff_baseline.py --write -- do not edit, do not merge by hand.\n"
    "# path RULE count. The list may only shrink; on a conflict, regenerate.\n"
)


def _split(text: str) -> tuple[str, str, str]:
    start = text.index(BEGIN) + len(BEGIN)
    return text[:start], text[start:text.index(END)], text[text.index(END):]


def offenders() -> dict[tuple[str, str], int]:
    """Count (path, rule) offences with the generated block taken out of the config."""
    head, _, tail = _split(PYPROJECT.read_text())
    with tempfile.TemporaryDirectory() as directory:
        config = Path(directory) / "pyproject.toml"
        config.write_text(head + tail)
        result = subprocess.run(  # noqa: S603, S607 -- fixed argument list, no shell
            ["ruff", "check", "--config", str(config), "--output-format", "json", "-q", str(ROOT)],  # noqa: S607 -- fixed command
            capture_output=True, text=True, check=False, cwd=ROOT)
    if result.returncode not in (0, 1):
        raise SystemExit(f"ruff failed:\n{result.stderr}")
    counts: dict[tuple[str, str], int] = {}
    for item in json.loads(result.stdout or "[]"):
        key = (str(Path(item["filename"]).relative_to(ROOT)), item["code"])
        counts[key] = counts.get(key, 0) + 1
    return counts


def read_baseline() -> dict[tuple[str, str], int]:
    counts: dict[tuple[str, str], int] = {}
    if BASELINE.exists():
        for line in BASELINE.read_text().splitlines():
            if line.strip() and not line.startswith("#"):
                path, rule, count = line.rsplit(" ", 2)
                counts[(path, rule)] = int(count)
    return counts


def render_baseline(counts: dict[tuple[str, str], int]) -> str:
    return HEADER + "".join(f"{path} {rule} {n}\n" for (path, rule), n in sorted(counts.items()))


def render_block(counts: dict[tuple[str, str], int]) -> str:
    rules: dict[str, list[str]] = {}
    for path, rule in sorted(counts):
        rules.setdefault(path, []).append(rule)
    return "".join(f'"{path}" = [{", ".join(chr(34) + r + chr(34) for r in rs)}]\n'
                   for path, rs in rules.items())


def gained(current: dict[tuple[str, str], int], allowed: dict[tuple[str, str], int]) -> list[str]:
    return [f"{path} {rule}: {n} found, {allowed.get((path, rule), 0)} listed"
            for (path, rule), n in sorted(current.items()) if n > allowed.get((path, rule), 0)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    current = offenders()
    if args.write:
        BASELINE.parent.mkdir(exist_ok=True)
        BASELINE.write_text(render_baseline(current))
        head, _, tail = _split(PYPROJECT.read_text())
        PYPROJECT.write_text(head + render_block(current) + tail)
        print(f"{len(current)} entries, {sum(current.values())} offences")
        return 0

    problems = gained(current, read_baseline())
    _, block, _ = _split(PYPROJECT.read_text())
    if block != render_block(read_baseline()):
        problems.append("the generated block in pyproject.toml is not quality/ruff-ignores.txt; "
                        "run tools/ruff_baseline.py --write")
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
